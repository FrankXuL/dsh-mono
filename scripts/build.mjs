// Concatenates src/client/** into the root client.js: no bundler, no dependency
// graph analysis, one fixed order. Every chunk is a plain script fragment that
// shares the factory scope, so later chunks may use earlier bindings.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Fixed order. Add a module here when you add a file. */
const MODULES = [
  "src/client/base.js",
  // Pure layout functions first: PaneTree renders their output, and a const
  // used before its definition is a TDZ error, not a hoisted reference.
  "src/client/layout/tree.js",
  // Tabs and layout live outside React: the host unmounts the panel whenever it
  // reveals a session itself, and the tabs have to survive that.
  "src/client/state/workspace.js",
  "src/client/session/reference.js",
  "src/client/panes/Pane.js",
  "src/client/panes/SessionPicker.js",
  "src/client/panes/TabStrip.js",
  "src/client/panes/PaneTree.js",
  "src/client/persist/index.js",
];

const STYLE = "src/client/style.css";
const ENTRY = "src/client/index.js";

const read = (path) => readFile(join(ROOT, path), "utf8");

const chunks = [];
for (const path of MODULES) chunks.push(await read(path));
chunks.push(`/** CSS text, inlined from ${STYLE}. */
const MONO_STYLE_TEXT = ${JSON.stringify(await read(STYLE))};`);
chunks.push(await read(ENTRY));

const indent = (text) =>
  text
    .replace(/\s+$/, "")
    .split("\n")
    .map((line) => (line === "" ? "" : "    " + line))
    .join("\n");

const body = chunks.map(indent).join("\n\n");

const output = `// Generated by scripts/build.mjs from src/client/** — edit those files, then
// run: npm run build. Do not edit this file by hand.
window.__ModuleLoader__.load({
  id: "dsh-mono",
  factory(require) {
    const react = require("react");
    const h = react.createElement;

${body}

    return MONO_PLUGIN;
  },
});
`;

await writeFile(join(ROOT, "client.js"), output);
console.log("client.js built from " + chunks.length + " chunks (" + Buffer.byteLength(output) + " bytes)");
